#!/usr/bin/env python3
"""Build a traceability matrix HLR -> LLR -> test case -> result.

Usage:
  trace_matrix.py HLR.sdoc LLR.sdoc test_file.c unity_results.txt > matrix.md

Inputs:
  *.sdoc            StrictDoc requirement documents (UID, TITLE, RELATIONS/Parent)
  test_file.c       tests tagged "// @TC TC-NNN @verifies LLR-NNN ... @type T"
                    on the line just above "void test_xxx(void)"
  unity_results.txt Unity output lines "file:line:test_name:PASS|FAIL[:msg]"

Exit status is 1 if any traceability gap or test failure is found, so CI fails.
"""
import re
import sys
from collections import OrderedDict


def read_sdoc(path):
    """Return OrderedDict uid -> {'title': str, 'parents': [uid]}."""
    reqs = OrderedDict()
    current = None
    in_relations = False
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("[REQUIREMENT]"):
                current = {"uid": None, "title": "", "parents": []}
                in_relations = False
                continue
            if current is None:
                continue
            m = re.match(r"^UID:\s*(\S+)", line)
            if m:
                current["uid"] = m.group(1)
                reqs[current["uid"]] = current
                continue
            m = re.match(r"^TITLE:\s*(.+)", line)
            if m:
                current["title"] = m.group(1).strip()
                continue
            if line.startswith("RELATIONS:"):
                in_relations = True
                continue
            if in_relations:
                m = re.match(r"^\s+VALUE:\s*(\S+)", line)
                if m:
                    current["parents"].append(m.group(1))
                elif line and not line.startswith(" ") and not line.startswith("-"):
                    in_relations = False
    return reqs


def read_tests(path):
    """Return OrderedDict function_name -> {'tc', 'verifies', 'type'}."""
    tests = OrderedDict()
    tag = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^\s*//\s*@TC\s+(\S+)\s+@verifies\s+(.+?)\s+@type\s+(\S+)", line)
            if m:
                tag = {"tc": m.group(1), "verifies": m.group(2).split(), "type": m.group(3)}
                continue
            m = re.match(r"^\s*void\s+(test_\w+)\s*\(", line)
            if m and tag:
                tests[m.group(1)] = tag
                tag = None
    return tests


def read_results(path):
    """Return dict function_name -> 'PASS' | 'FAIL' | 'IGNORE'."""
    results = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^[^:]+:\d+:(test_\w+):(PASS|FAIL|IGNORE)", line.strip())
            if m:
                results[m.group(1)] = m.group(2)
    return results


def main():
    if len(sys.argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    hlrs = read_sdoc(sys.argv[1])
    llrs = read_sdoc(sys.argv[2])
    tests = read_tests(sys.argv[3])
    results = read_results(sys.argv[4])

    llr_to_tests = {uid: [] for uid in llrs}
    gaps = []
    for fn, t in tests.items():
        for uid in t["verifies"]:
            if uid in llr_to_tests:
                llr_to_tests[uid].append(fn)
            else:
                gaps.append(f"{t['tc']} ({fn}) verifies unknown requirement {uid}")
        if fn not in results:
            gaps.append(f"{t['tc']} ({fn}) has no execution result")
        elif results[fn] != "PASS":
            gaps.append(f"{t['tc']} ({fn}) result is {results[fn]}")

    hlr_to_llrs = {uid: [] for uid in hlrs}
    for uid, r in llrs.items():
        if not r["parents"]:
            gaps.append(f"{uid} has no parent HLR")
        for p in r["parents"]:
            if p in hlr_to_llrs:
                hlr_to_llrs[p].append(uid)
            else:
                gaps.append(f"{uid} traces to unknown HLR {p}")
    for uid, children in hlr_to_llrs.items():
        if not children:
            gaps.append(f"{uid} is not refined by any LLR")
    for uid, fns in llr_to_tests.items():
        if not fns:
            gaps.append(f"{uid} is not verified by any test")

    out = []
    out.append("# Traceability matrix: parachute.c\n")
    out.append("Generated by `scripts/trace_matrix.py` from the requirement files, "
               "the test tags and the Unity test results.\n")

    out.append("## HLR -> LLR -> test cases\n")
    out.append("| HLR | LLR | LLR title | Test cases | Result |")
    out.append("|---|---|---|---|---|")
    for h, children in hlr_to_llrs.items():
        for l in children or ["-"]:
            fns = llr_to_tests.get(l, [])
            tcs = ", ".join(tests[fn]["tc"] for fn in fns) or "NONE"
            ok = fns and all(results.get(fn) == "PASS" for fn in fns)
            status = "PASS" if ok else "GAP"
            title = llrs[l]["title"] if l in llrs else ""
            out.append(f"| {h} | {l} | {title} | {tcs} | {status} |")

    out.append("\n## Test cases\n")
    out.append("| Test case | Function | Type | Verifies | Result |")
    out.append("|---|---|---|---|---|")
    for fn, t in tests.items():
        out.append(f"| {t['tc']} | `{fn}` | {t['type']} | {', '.join(t['verifies'])} "
                   f"| {results.get(fn, 'NOT RUN')} |")

    out.append("\n## Summary\n")
    n_pass = sum(1 for fn in tests if results.get(fn) == "PASS")
    out.append(f"- HLRs: {len(hlrs)}, LLRs: {len(llrs)}, test cases: {len(tests)}, "
               f"passed: {n_pass}/{len(tests)}")
    if gaps:
        out.append(f"- **Gaps found: {len(gaps)}**")
        out.extend(f"  - {g}" for g in gaps)
    else:
        out.append("- No traceability gaps: every HLR is refined by an LLR, every LLR is "
                   "verified by at least one test, and every test passed.")
    print("\n".join(out))
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
